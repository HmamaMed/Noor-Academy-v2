CREATE TABLE contact_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(254) NOT NULL,
    subject VARCHAR(160) NOT NULL,
    message VARCHAR(5000) NOT NULL,
    is_read BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_contact_messages_created ON contact_messages (created_at DESC, id DESC);
CREATE INDEX idx_contact_messages_email ON contact_messages (email, created_at);

CREATE TABLE footer_settings (
    id BIGINT PRIMARY KEY CHECK (id = 1),
    email VARCHAR(254) NOT NULL DEFAULT '',
    phone VARCHAR(40) NOT NULL DEFAULT '',
    instagram_url VARCHAR(500) NOT NULL DEFAULT '',
    facebook_url VARCHAR(500) NOT NULL DEFAULT '',
    whatsapp_url VARCHAR(500) NOT NULL DEFAULT '',
    location_name VARCHAR(160) NOT NULL DEFAULT '',
    address VARCHAR(300) NOT NULL DEFAULT '',
    latitude DOUBLE PRECISION,
    longitude DOUBLE PRECISION,
    CONSTRAINT valid_footer_coordinates CHECK (
        (latitude IS NULL AND longitude IS NULL) OR
        (latitude IS NOT NULL AND longitude IS NOT NULL AND latitude BETWEEN -85 AND 85 AND longitude BETWEEN -180 AND 180)
    )
);
