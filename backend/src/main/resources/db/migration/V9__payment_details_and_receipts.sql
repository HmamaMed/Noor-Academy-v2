CREATE TABLE payment_settings (
    id BIGINT PRIMARY KEY CHECK (id = 1),
    bank_name VARCHAR(160) NOT NULL DEFAULT '',
    account_holder VARCHAR(160) NOT NULL DEFAULT '',
    rib VARCHAR(80) NOT NULL DEFAULT '',
    bank_instructions VARCHAR(1000) NOT NULL DEFAULT '',
    visit_instructions VARCHAR(1000) NOT NULL DEFAULT '',
    opening_hours VARCHAR(300) NOT NULL DEFAULT ''
);
